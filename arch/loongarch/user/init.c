#include "kernel/arch/user.h"

/*
 * Minimal LoongArch user image used by user_init().  It invokes exec("/init")
 * through the LoongArch syscall ABI.  The PC-relative address of path is
 * resolved for an image loaded at virtual address zero.
 */
static const uint8 init_code[] = {
    0x04, 0x00, 0x00, 0x1a, 0x84, 0x70, 0xc0, 0x02, 0x0b, 0x74, 0xc3, 0x02,
    0x00, 0x00, 0x2b, 0x00, 0x04, 0x00, 0xc0, 0x02, 0x0b, 0x74, 0xc1, 0x02,
    0x00, 0x00, 0x2b, 0x00, 0x2f, 0x69, 0x6e, 0x69, 0x74, 0x00,
};

const uint8 *arch_user_init_code(void)
{
	return init_code;
}

uint64 arch_user_init_code_size(void)
{
	return sizeof(init_code);
}
