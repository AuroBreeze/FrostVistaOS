#include "kernel/arch/user.h"

/*
 * Minimal RISC-V user image used by user_init().  It invokes exec("/init")
 * through the RISC-V syscall ABI.  Keep this image in the RISC-V backend;
 * it must never be shared with another instruction-set architecture.
 */
static const uint8 init_code[] = {
	0x17, 0x05, 0x00, 0x00, 0x13, 0x05, 0x45, 0x02, 0x97, 0x05, 0x00,
	0x00, 0x93, 0x85, 0x35, 0x02, 0x93, 0x08, 0xd0, 0x0d, 0x73, 0x00,
	0x00, 0x00, 0x93, 0x08, 0xd0, 0x05, 0x73, 0x00, 0x00, 0x00, 0xef,
	0xf0, 0x9f, 0xff, 0x2f, 0x69, 0x6e, 0x69, 0x74, 0x00, 0x00, 0x24,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
};

const uint8 *arch_user_init_code(void)
{
	return init_code;
}

uint64 arch_user_init_code_size(void)
{
	return sizeof(init_code);
}
